"""Rust data shapes for the canonical contract."""
from __future__ import annotations

import json

from .common import variant_name

VALIDATE = r'''
fn valid(kind: &str, value: &str) -> bool {
    let hex = |s: &str| s.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b));
    match kind {
        "hex32" => value.len() == 64 && hex(value),
        "uuid" => value.len() == 36 && value.bytes().enumerate().all(|(i, b)| {
            if [8, 13, 18, 23].contains(&i) { b == b'-' } else { b.is_ascii_digit() || (b'a'..=b'f').contains(&b) }
        }),
        "i32" => value.parse::<i32>().is_ok_and(|n| n.to_string() == value),
        "u32" | "u64" => !value.is_empty() && (value == "0" || !value.starts_with('0'))
            && value.bytes().all(|b| b.is_ascii_digit())
            && if kind == "u32" { value.parse::<u32>().is_ok() } else { value.parse::<u64>().is_ok() },
        "sid-hex" => value.len() >= 16 && value.len() <= 136 && hex(value) && value.starts_with("01")
            && u8::from_str_radix(&value[2..4], 16).is_ok_and(|n| n <= 15 && value.len() == 16 + usize::from(n) * 8),
        _ => false,
    }
}
'''


def render(meta: dict, rows: list[dict], digest: str) -> str:
    domain = json.dumps(meta["device_id_domain"]).replace(r"\u0000", r"\0")
    output = [f'// Generated by scripts/generate_node_contract.py. Decoded values are untrusted data.\n'
              f'pub const CONTRACT_VERSION: u32 = {meta["version"]};\n'
              f'pub const SCHEMA_SHA256: &str = "{digest}";\n'
              f'pub const DEVICE_ID_DOMAIN: &[u8] = b{domain};\n', VALIDATE]
    optional = {row["name"] for row in rows if row["kind"] == "optional"}
    if optional:
        output.append("fn required_optional<'de, D: serde::Deserializer<'de>, T: serde::Deserialize<'de>>(d: D) -> Result<T, D::Error> { T::deserialize(d) }\n")
    for row in rows:
        name = row["name"]
        if row["kind"] == "list":
            output.append(render_list(row))
        elif row["kind"] == "optional":
            output.append(f'#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\n#[serde(transparent)]\npub struct {name}(pub Option<{row["item"]}>);\n')
        elif row["kind"] == "scalar" and row["encoding"] == "bool":
            output.append(f'#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\n#[serde(transparent)]\npub struct {name}(pub bool);\n')
        elif row["kind"] == "scalar":
            debug = "" if row.get("secret") else ", Debug"
            validation = f'valid("{row["encoding"]}", &value)'
            if row["encoding"] == "text":
                validation = f'value.len() >= {row["min_bytes"]} && value.len() <= {row["max_bytes"]} && !value.chars().any(char::is_control)'
            if row["encoding"] == "bytes":
                validation = f"""value.len() >= {row['min_bytes'] * 2} && value.len() <= {row['max_bytes'] * 2} && value.len() % 2 == 0 && value.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))"""
            if "minimum" in row:
                validation += f' && value.parse::<{row["encoding"]}>().is_ok_and(|n| ({row["minimum"]}..={row["maximum"]}).contains(&n))'
            output.append(f'''#[derive(Clone, PartialEq, Eq, Hash{debug}, serde::Serialize, serde::Deserialize)]
#[serde(try_from = "String", into = "String")]
pub struct {name}(String);
impl {name} {{ pub fn as_str(&self) -> &str {{ &self.0 }} }}
impl TryFrom<String> for {name} {{
    type Error = &'static str;
    fn try_from(value: String) -> Result<Self, Self::Error> {{
        if {validation} {{ Ok(Self(value)) }} else {{ Err("invalid {name}") }}
    }}
}}
impl From<{name}> for String {{ fn from(value: {name}) -> Self {{ value.0 }} }}
''')
            if row.get("secret"):
                output.append(f'impl std::fmt::Debug for {name} {{ fn fmt(&self, f: &mut std::fmt::Formatter<\'_>) -> std::fmt::Result {{ f.write_str("{name}([redacted])") }} }}\n')
            if row["encoding"] in {"u32", "u64"} and "minimum" not in row:
                primitive = row["encoding"]
                output.append(f'impl From<{primitive}> for {name} {{ fn from(value: {primitive}) -> Self {{ Self(value.to_string()) }} }}\n')
        elif row["kind"] == "record":
            fields = "\n".join(('    #[serde(deserialize_with = "required_optional")]\n' if field["type"] in optional else "")
                               + f'    pub {field["name"]}: {field["type"]},' for field in row["fields"])
            output.append(f'#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct {name} {{\n{fields}\n}}\n')
        else:
            variants = "\n".join(f'    #[serde(rename = "{variant["tag"]}")]\n    {variant_name(variant["tag"])}({variant["type"]}),' for variant in row["variants"])
            output.append(f'#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\n#[serde(tag = "{row["tag"]}", content = "value", deny_unknown_fields)]\npub enum {name} {{\n{variants}\n}}\n')
    output.append('''pub fn device_id_for_public_key(key: &Ed25519PublicKey) -> DeviceId {
    use sha2::{Digest, Sha256};
    let mut hash = Sha256::new();
    hash.update(DEVICE_ID_DOMAIN);
    for index in (0..64).step_by(2) {
        hash.update([u8::from_str_radix(&key.as_str()[index..index + 2], 16).expect("validated public key")]);
    }
    DeviceId(format!("{:x}", hash.finalize()))
}
''')
    return "\n".join(output)


def render_list(row: dict) -> str:
    name, item, maximum = row["name"], row["item"], row["max_items"]
    return f'''#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(try_from = "Vec<{item}>", into = "Vec<{item}>")]
pub struct {name}(Vec<{item}>);
impl {name} {{ pub fn as_slice(&self) -> &[{item}] {{ &self.0 }} }}
impl TryFrom<Vec<{item}>> for {name} {{
    type Error = &'static str;
    fn try_from(value: Vec<{item}>) -> Result<Self, Self::Error> {{
        if value.len() <= {maximum} {{ Ok(Self(value)) }} else {{ Err("too many {name} items") }}
    }}
}}
impl From<{name}> for Vec<{item}> {{ fn from(value: {name}) -> Self {{ value.0 }} }}
'''
