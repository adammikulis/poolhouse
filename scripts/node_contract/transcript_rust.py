def render(model: dict) -> str:
    domains = {profile["name"]: profile["domain"] for profile in model["profile"]}
    def literal(value: str) -> str:
        return "b" + json.dumps(value).replace(r"\u0000", r"\0")
    return TEMPLATE.replace("@APPROVAL_DOMAIN@", literal(domains["approval-immutable-v1"])).replace(
        "@SCOPED_DOMAIN@", literal(domains["local-authority-scoped-v1"]))
