"""TypeScript public data shapes for the canonical contract."""
from __future__ import annotations


def render(meta: dict, rows: list[dict], digest: str) -> str:
    output = [f'// Generated by scripts/generate_node_contract.py. Decoded values are untrusted data.\n'
              f'export const CONTRACT_VERSION = {meta["version"]} as const;\n'
              f'export const SCHEMA_SHA256 = "{digest}" as const;\n']
    for row in rows:
        if row["visibility"] != "public":
            continue
        name = row["name"]
        if row["kind"] == "scalar":
            output.append(f'export type {name} = string & {{ readonly __{name}: unique symbol }};\n')
        elif row["kind"] == "record":
            fields = "\n".join(f'  readonly {field["name"]}: {field["type"]};' for field in row["fields"])
            output.append(f'export interface {name} {{\n{fields}\n}}\n')
        else:
            variants = [f'{{ readonly {row["tag"]}: "{variant["tag"]}"; readonly value: {variant["type"]} }}' for variant in row["variants"]]
            output.append(f'export type {name} = ' + " | ".join(variants) + ";\n")
    return "\n".join(output)
