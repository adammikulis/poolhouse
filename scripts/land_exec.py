"""What a landing checks for a diff, and running the checks in a clean environment and a process group of their own."""

from __future__ import annotations

import contextlib
import os
import re
import select
import signal
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

import affected
import land_git as lg

FULL_FILES = 120
FULL_LINES = 4000
INFRA = re.compile(r"^(tests/conftest\.py|scripts/test[^/]*|scripts/testslots[^/]*|pyproject\.toml|packaging/.*)$")
DOC = re.compile(r"^([^/]+\.md|docs/.*)$")
FAILED = re.compile(r"^(?:FAILED|ERROR) (\S+)", re.M)
KEEP = ("PATH", "HOME", "USER", "LOGNAME", "LANG", "LC_ALL", "LC_CTYPE", "TERM", "TMPDIR", "POOLHOUSE_HOME", "POOLHOUSE_BOARD",
        "POOLHOUSE_WORKSPACE_AGENT", "POOLHOUSE_DEV_BRANCH", "DEV_TEST_SLOTS_DIR")
CACHES = re.compile(
    r"(^|/)(__pycache__|\.pytest_cache|\.ruff_cache|\.mypy_cache|node_modules|\.venv|\.build-venv|\.build-work)(/|$)"
    r"|^(dist|build|packaging/build|app/target|app/src-tauri/(binaries|gen|permissions/autogenerated))(/|$)"
    r"|^tests/_generated_[^/]*|(^|/)\.testmondata[^/]*$|\.py[cod]$|\.egg-info(/|$)|^\.full-tier-last\.json$")
CONTROL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")
TAIL = 40


class Stop(Exception):
    """The landing stops here; the message is the one line the caller reads, ``tail`` the end of the output behind it."""

    def __init__(self, message: str, tail: list[str] | None = None) -> None:
        super().__init__(message)
        self.tail = tail or []


@dataclass
class Check:
    """One verification step: a name and the command."""

    name: str
    argv: list[str]
    files: list[str] = field(default_factory=list)


@dataclass
class Plan:
    """The checks a diff needs, the kind of diff and why the whole suite runs, if it does."""

    kind: str
    checks: list[Check]
    full: str = ""
    changed: list[str] = field(default_factory=list)


def printable(text: str) -> str:
    """``text`` without control characters, so output from a check cannot drive the caller's terminal."""
    return CONTROL.sub("", text)


def needs_full(root: Path, base: str, sha: str, changed: list[str], unmapped: list[str]) -> str:
    """Why the whole suite runs for this diff, or an empty string."""
    infra = [p for p in changed if INFRA.match(p)]
    if infra:
        return f"shared infrastructure touched: {infra[0]}"
    if unmapped:
        return f"no selector maps {unmapped[0]}"
    rows = (r.split("\t") for r in lg.lines(root, "diff", "--numstat", base, sha))
    lines = sum(int(a) + int(b) for a, b, *_ in rows if a.isdigit() and b.isdigit())
    if len(changed) > FULL_FILES or lines > FULL_LINES:
        return f"{len(changed)} files, {lines} lines exceed the diff threshold"
    return ""


def plan(wt: Path, base: str, sha: str) -> Plan:
    """The checks for the diff of ``sha`` against ``base``, chosen from the tree of ``wt``."""
    changed = lg.lines(wt, "diff", "--name-only", "--no-renames", base, sha)
    if not changed:
        return Plan("none", [])
    py = sys.executable
    gone = frozenset(p for p in changed if not (wt / p).exists())
    pick = affected.select(wt, changed, gone, base=base)
    files = sorted(pick.files)
    docs = all(DOC.match(p) for p in changed)
    checks = ([Check("budgets", [py, "scripts/budgets"]), Check("clean-diff", ["git", "diff", "--check", base, sha])]
              if docs else [Check("gate", [py, "scripts/test", "gate"])])
    if files:
        checks.append(Check("affected", [py, "scripts/test", "all", *files], files))
    full = needs_full(wt, base, sha, changed, pick.unmapped)
    if full:
        checks.append(Check("full", [py, "scripts/test", "full"]))
    return Plan("docs" if docs else "code", checks, full, changed)


def check_env(wt: Path) -> dict[str, str]:
    """The environment a check runs in: a short list of the caller's variables and the lander's own."""
    env = {name: os.environ[name] for name in KEEP if name in os.environ}
    env["PYTHONPATH"] = os.pathsep.join((str(wt / "src"), str(wt / "scripts")))
    env["POOLHOUSE_GATE_TREE_ONLY"] = "1"
    return env


def snapshot(wt: Path) -> tuple[str, list[str]]:
    """The git tree of every file in ``wt`` that is not ignored, and the ignored paths that are not build caches."""
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    with tempfile.TemporaryDirectory() as scratch:
        env["GIT_INDEX_FILE"] = str(Path(scratch) / "index")
        lg.git(wt, "add", "-A", env=env)
        tree = lg.git(wt, "write-tree", env=env).stdout.strip()
    ignored = lg.git(wt, "ls-files", "-z", "--others", "--ignored", "--exclude-standard", "--directory", env=env).stdout.split("\0")
    return tree, [p for p in ignored if p and not CACHES.search(p)]


def verify_tree(wt: Path, tree: str) -> None:
    """Stop unless ``wt`` still holds exactly ``tree`` and no ignored file besides build caches."""
    now, strays = snapshot(wt)
    if strays:
        raise Stop(f"ignored files that are not build caches are in the worktree: {', '.join(strays[:5])}")
    if now != tree:
        raise Stop("the worktree no longer holds the tree that was selected for testing")


def kill_group(proc: subprocess.Popen) -> None:
    """End every process of the group ``proc`` leads."""
    with contextlib.suppress(ProcessLookupError, PermissionError):
        os.killpg(proc.pid, signal.SIGKILL)
    proc.wait()


def emit(raw: bytes, seen: list[str]) -> None:
    """Echo one line of a check's output and keep it."""
    line = printable(raw.decode("utf-8", "replace").rstrip("\r"))
    seen.append(line)
    print(f"  {line}", flush=True)


def run_check(wt: Path, check: Check) -> tuple[int, list[str]]:
    """Run ``check`` in its own process group, echo its output and return the status and the lines.

    The output ends when the check exits, even if a process it left behind still holds the pipe; the group is then killed.
    """
    proc = subprocess.Popen(check.argv, cwd=wt, env=check_env(wt), stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, start_new_session=True)
    seen: list[str] = []
    pending = b""
    try:
        fd = proc.stdout.fileno() if proc.stdout else -1
        while fd >= 0:
            if select.select([fd], [], [], 0.2)[0]:
                chunk = os.read(fd, 65536)
                if not chunk:
                    break
                *whole, pending = (pending + chunk).split(b"\n")
                for raw in whole:
                    emit(raw, seen)
            elif proc.poll() is not None:
                break
        if pending:
            emit(pending, seen)
        return proc.wait(), seen
    finally:
        kill_group(proc)


def failed_tests(lines: list[str]) -> list[str]:
    """The test ids a pytest short summary names as failed or errored."""
    return sorted(dict.fromkeys(FAILED.findall("\n".join(lines))))


def run_plan(wt: Path, checks: list[Check], tree: str) -> list[str]:
    """Run each check and return the last lines of the output; stop at the first red or if the tree changed under it."""
    tail: list[str] = []
    for check in checks:
        verify_tree(wt, tree)
        print(f"land: running {check.name}", flush=True)
        status, lines = run_check(wt, check)
        tail = lines[-TAIL:]
        verify_tree(wt, tree)
        if status:
            named = failed_tests(lines)
            label = "tests" if check.name in ("affected", "full") else check.name
            raise Stop(f"{label} failed" + (f": {', '.join(named[:10])}" if named else f" (exit {status})"), tail)
    return tail
