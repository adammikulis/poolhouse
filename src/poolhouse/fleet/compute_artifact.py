"""Immutable optional Studio compute code associated with a minimal runtime wheel."""
from __future__ import annotations

import hashlib
import json
import re
import shutil
import stat
import zipfile
from email.parser import BytesParser
from pathlib import Path, PurePosixPath

from packaging.version import Version

from poolhouse.files import writing
from poolhouse.fleet.wheel_provenance import write_wheel
from poolhouse.net import packages

MANIFEST = 'poolhouse/fleet/compute-artifact.json'
DISTRIBUTION = 'poolhouse-studio-compute'
PREFIXES = tuple(f'poolhouse/{name}/' for name in ('train', 'bench', 'gym', 'world'))
ROLE = 'studio-compute'


def contents(wheel: Path) -> dict[str, bytes]:
    """Read a wheel whose file names are unique, confined and regular."""
    if wheel.is_symlink() or not wheel.is_file():
        raise ValueError('Compute artifact must be a regular file')
    with zipfile.ZipFile(wheel) as archive:
        rows = archive.infolist()
        names = [row.filename for row in rows]
        if len(set(names)) != len(names):
            raise ValueError('Compute artifact contains duplicate files')
        for row in rows:
            name = row.filename
            if '\\' in name or name.startswith('/') or '..' in PurePosixPath(name).parts or stat.S_ISLNK(row.external_attr >> 16):
                raise ValueError('Compute artifact contains an unsafe file')
        return {row.filename: archive.read(row) for row in rows if not row.is_dir()}


def from_wheel(wheel: Path) -> dict | None:
    """Read the expected compute manifest embedded in the base wheel."""
    payload = contents(wheel).get(MANIFEST)
    return json.loads(payload) if payload is not None else None


def build(source: Path, wheel: Path, commit: str) -> Path:
    """Build the fixed companion from an unpacked immutable source revision."""
    if not re.fullmatch('[0-9a-f]{40}', commit):
        raise ValueError('Compute artifact requires a full source revision')
    base = contents(wheel)
    metadata = [value for name, value in base.items() if name.endswith('.dist-info/METADATA')]
    if len(metadata) != 1:
        raise ValueError('Base wheel must contain one metadata record')
    version = str(Version(BytesParser().parsebytes(metadata[0])['Version']))
    if not version or not re.fullmatch('[A-Za-z0-9.+!_-]+', version):
        raise ValueError('Base wheel has no valid version')
    files = {}
    for prefix in PREFIXES:
        root = source / 'src' / prefix
        if not root.is_dir() or root.is_symlink():
            raise ValueError('Committed source is missing a maintained compute package')
        for path in sorted(root.rglob('*')):
            if path.is_symlink():
                raise ValueError('Compute source cannot contain symbolic links')
            if path.is_file():
                if path.suffix == '.pyc' or '__pycache__' in path.parts:
                    raise ValueError('Compute source cannot contain generated bytecode')
                name = path.relative_to(source / 'src').as_posix()
                if name in base:
                    raise ValueError('Compute artifact overlaps the base wheel')
                files[name] = path.read_bytes()
    info = f'poolhouse_studio_compute-{version}.dist-info'
    origin = {'source': commit, 'role': ROLE, 'files': {name: hashlib.sha256(value).hexdigest() for name, value in files.items()}}
    files[f'{info}/METADATA'] = (f'Metadata-Version: 2.1\nName: {DISTRIBUTION}\nVersion: {version}\nRequires-Dist: poolhouse=={version}\n').encode()
    files[f'{info}/WHEEL'] = b'Wheel-Version: 1.0\nGenerator: poolhouse\nRoot-Is-Purelib: true\nTag: py3-none-any\n'
    files[f'{info}/compute-origin.json'] = json.dumps(origin, sort_keys=True).encode()
    files[f'{info}/RECORD'] = b''
    companion = wheel.with_name(f'poolhouse_studio_compute-{version}-py3-none-any.whl')
    write_wheel(companion, files)
    manifest = {'source': commit, 'role': ROLE, 'distribution': DISTRIBUTION, 'version': version,
                'filename': companion.name, 'sha256': hashlib.sha256(companion.read_bytes()).hexdigest(),
                'files': {name: hashlib.sha256(value).hexdigest() for name, value in contents(companion).items()
                          if not name.endswith('.dist-info/RECORD')}}
    base[MANIFEST] = json.dumps(manifest, sort_keys=True).encode()
    write_wheel(wheel, base)
    (wheel.parent / 'compute-artifact.json').write_bytes(base[MANIFEST])
    return companion


def verify(wheel: Path, manifest: dict, commit: str) -> None:
    """Verify a companion against the expected base-owned manifest."""
    if manifest.get('source') != commit or manifest.get('role') != ROLE or manifest.get('distribution') != DISTRIBUTION:
        raise ValueError('Compute artifact does not match the app revision')
    if wheel.name != manifest.get('filename') or hashlib.sha256(wheel.read_bytes()).hexdigest() != manifest.get('sha256'):
        raise ValueError('Compute artifact integrity check failed')
    files = contents(wheel)
    expected = manifest.get('files', {})
    actual = {name: hashlib.sha256(value).hexdigest() for name, value in files.items() if not name.endswith('.dist-info/RECORD')}
    if actual != expected:
        raise ValueError('Compute artifact file inventory does not match')
    info = f"poolhouse_studio_compute-{manifest['version']}.dist-info/"
    if any(not name.startswith((*PREFIXES, info)) for name in files):
        raise ValueError('Compute artifact contains files outside its fixed packages')
    allowed_info = {info + name for name in ('METADATA', 'WHEEL', 'RECORD', 'compute-origin.json')}
    if any(name.startswith(info) and name not in allowed_info for name in files):
        raise ValueError('Compute artifact contains unexpected distribution files')
    metadata = BytesParser().parsebytes(files[info + 'METADATA'])
    origin = json.loads(files[info + 'compute-origin.json'])
    package_files = {name: hashlib.sha256(value).hexdigest() for name, value in files.items() if name.startswith(PREFIXES)}
    if origin.get('files') != package_files:
        raise ValueError('Compute artifact source inventory does not match')
    if metadata['Name'] != DISTRIBUTION or metadata['Version'] != manifest['version'] or origin.get('source') != commit or origin.get('role') != ROLE:
        raise ValueError('Compute artifact metadata does not match the app')


def cache(base: Path, target: Path, commit: str) -> None:
    """Cache a verified companion beside its owning base runtime wheel."""
    manifest = from_wheel(base)
    if manifest is None:
        return
    companion = base.with_name(manifest['filename'])
    verify(companion, manifest, commit)
    with writing(target.with_name(companion.name)) as temporary:
        shutil.copyfile(companion, temporary)


def expected() -> dict:
    """Return the manifest shipped by the imported app, never a cache claim."""
    path = Path(__file__).with_name('compute-artifact.json')
    if not path.is_file() or path.is_symlink():
        raise OSError('This app has no bundled compute artifact; update the installed app')
    manifest = json.loads(path.read_text())
    if not re.fullmatch('[0-9a-f]{40}', manifest.get('source', '')):
        raise OSError('The app compute manifest has no immutable source revision')
    return manifest


